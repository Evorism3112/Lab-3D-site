import { inflateRawSync } from "zlib";

// What a sliced file says about itself, so the admin can see which slicer really made it.
// deploy/slicer-test.mjs has its own copy (plain Node, it can't import this).

const TEXT_LIMIT = 200_000;
/** Header patterns: the 3MF model metadata and the G-code header both name the slicer. */
const MARKERS = [/<metadata name="Application">([^<]+)</, /; generated by ([^\r\n]+?)(?: on \d|\r?\n)/];

function findMarker(text: string): string | null {
  for (const marker of MARKERS) {
    const found = text.match(marker);
    if (found) return found[1].trim();
  }
  return null;
}

/** "OrcaSlicer-2.4.2", "BambuStudio 02.08.02.61"…, or null when the file doesn't say. */
export function slicedBy(file: Buffer): string | null {
  try {
    return readSlicedBy(file);
  } catch {
    // A damaged or unexpected file: we just don't know.
    return null;
  }
}

function readSlicedBy(file: Buffer): string | null {
  const eocd = file.lastIndexOf(Buffer.from([0x50, 0x4b, 0x05, 0x06]));
  // Not a zip: plain G-code.
  if (eocd < 0) return findMarker(file.toString("utf8", 0, TEXT_LIMIT));

  const entries: { name: string; method: number; size: number; local: number }[] = [];
  let at = file.readUInt32LE(eocd + 16);
  for (let i = file.readUInt16LE(eocd + 10); i > 0 && at + 46 <= file.length; i--) {
    const nameLength = file.readUInt16LE(at + 28);
    entries.push({
      name: file.toString("utf8", at + 46, at + 46 + nameLength),
      method: file.readUInt16LE(at + 10),
      size: file.readUInt32LE(at + 20),
      local: file.readUInt32LE(at + 42),
    });
    at += 46 + nameLength + file.readUInt16LE(at + 30) + file.readUInt16LE(at + 32);
  }
  // The small metadata files first; the G-code (can be huge) only when they don't tell.
  const rank = (name: string) => (/3dmodel\.model$/i.test(name) ? 0 : /slice_info\.config$/i.test(name) ? 1 : /\.gcode$/i.test(name) ? 2 : -1);
  const wanted = entries.filter((e) => rank(e.name) >= 0).sort((a, b) => rank(a.name) - rank(b.name));
  for (const entry of wanted) {
    try {
      const start = entry.local + 30 + file.readUInt16LE(entry.local + 26) + file.readUInt16LE(entry.local + 28);
      const raw = file.subarray(start, start + entry.size);
      const text = (entry.method === 8 ? inflateRawSync(raw) : raw).toString("utf8", 0, TEXT_LIMIT);
      const found = findMarker(text);
      if (found) return found;
    } catch {
      // A damaged entry just doesn't count.
    }
  }
  return null;
}

/** Binary STL of a 20 × 20 × 20 mm cube (8 cm³), for the admin's test slice. */
export function testCubeStl(): Buffer {
  const v = [[0, 0, 0], [20, 0, 0], [20, 20, 0], [0, 20, 0], [0, 0, 20], [20, 0, 20], [20, 20, 20], [0, 20, 20]];
  const faces = [[0, 2, 1], [0, 3, 2], [4, 5, 6], [4, 6, 7], [0, 1, 5], [0, 5, 4], [1, 2, 6], [1, 6, 5], [2, 3, 7], [2, 7, 6], [3, 0, 4], [3, 4, 7]];
  const buf = Buffer.alloc(84 + faces.length * 50);
  buf.writeUInt32LE(faces.length, 80);
  let offset = 84;
  for (const face of faces) {
    offset += 12;
    for (const i of face) for (const c of v[i]) { buf.writeFloatLE(c, offset); offset += 4; }
    offset += 2;
  }
  return buf;
}
